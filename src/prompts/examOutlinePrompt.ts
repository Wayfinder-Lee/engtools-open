/**
 * 试卷大纲切块 prompt：一次便宜调用，让 LLM 列出全文的大题清单及
 * 各大题标题行（或正文开头）的原文锚点，用于替代/校正本地正则切块
 * 在格式混乱试卷上的错位。输出仅一个短 JSON（不是逐题解析）。
 */

export function buildExamOutlinePrompt(manifest: readonly string[], candidateNames: readonly string[]): string {
  const manifestLine = manifest.length > 0
    ? `用户声明本卷应包含的大题题型（供参考；顺序可能与原文不同，一切以原文实际为准，可以多也可以少）：${manifest.join('、')}`
    : '用户未声明题型清单，请按原文实际内容识别大题。';
  const candidateLine = candidateNames.length > 0
    ? `本地正则初步识别到的大题（可能有错漏，仅供参照）：${candidateNames.join('、')}`
    : '本地正则未能识别出任何大题（这份卷子格式很可能不标准，请仔细找）。';

  return `你是试卷结构分析器。输入是一份英语试卷全文（可能从 Word/PDF 复制而来，换行、页码、格式混乱）。请找出所有顶级大题（如 听力理解、阅读理解A、完形填空、语法填空、书面表达 等）在原文中的位置。

${manifestLine}
${candidateLine}

## 任务
按原文出现顺序列出每个大题，并为每个大题给出一个能在原文中唯一定位的锚点（startMark）。
同时检查文档末尾是否带非试题的附加部分（参考答案、答案详解、听力原文等），在 appendices 里列出。

## startMark 要求（最关键字段）
- 从原文**逐字复制** 8~20 个字符，禁改写、禁翻译、禁补标点。
- 优先摘该大题标题行的开头（如「第二部分 听力（共两节」「第一节：单项选择」）。
- 锚点必须优先取该大题的标题行（第X部分/第X节/题型名行）；大题标题只是「第一节（满分25分）」这类无题型名的节行时，锚点取该节行本身，**禁止**取正文、故事、材料的第一句。
- 每个大题恰好输出一个条目：同一大题的中文指令句与英文材料/题目属于同一大题，禁止拆成两个条目（如读后续写的「阅读下面的材料…」与故事正文是一个大题）。
- 大题没有明确标题行时（如阅读各篇只有独立字母 A/B/C/D），摘该大题**正文第一句的开头**（英文原句前 10~20 个字符）。
- 锚点必须落在该大题自己的内容起始处，不能摘到上一大题的结尾或页眉。

## 识别规则
- 只列顶级大题；大题内部的「第一节/第二节」不单独列。
- 大题的中文指令句（如「根据短文内容，从短文后的七个选项中选出能填入空白处的最佳选项」）不是独立大题：它与其后的正文/选项属于**同一个大题**，锚点落在指令行时 name 按指令内容判型（七选五/语法填空等），**禁止沿用上一个阅读篇的字母名**（如把七选五的指令行标成「阅读理解D」）。
- 节标题行（如「第二节（共5小题；每小题2分，共10分）」）与其后的指令句、正文同属**同一个大题**，不得作为独立大题单列，也不得沿用上一个阅读篇的字母名——它标示的是其后新题型（七选五等）的开始。
- 阅读理解各篇 A/B/C/D 若各自独立成篇，分别列出（name 用 阅读理解A、阅读理解B…）。
- name 用规范题型名，与用户清单同名优先；清单外确实存在的题型也要列出，用原文标题命名。
- **name 必须忠实于该大题自己标题行的题型名**：清单只是先验，地方卷特有题型（如「阅读表达」「回答问题」「作文」「任务型阅读」）在原文有明确标题时，name 就用原文标题，**禁止把清单里最相近的名字硬套上去**（例如把「阅读表达」标成「应用文写作」、「作文」标成「读后续写」——题型与排版完全不同）。
- 未在原文出现的大题**不要**列出（哪怕清单里有）。

## 附加部分规则（appendices）
- 只收所有大题正文之后、位于文档末尾的附加部分（参考答案、答案详解、听力原文等）。
- 每条输出 label（附加部分原标题，如「参考答案及解析」）+ startMark（其标题行开头逐字复制 4~20 个字符；标题行不足 4 字时连同行内后续文字凑足）。
- 同一文档多个附录标题的开头相同（如「××考试英语听力材料」与「××考试英语参考答案」）时，各条 startMark 必须向后延伸到能区分两者的字（上限 30 字符）——前缀相同的 startMark 会在定位时坍缩到同一处，后一个附录被静默吞掉。
- 附加部分的内容**不列入 sections**——它是答案/材料不是试题，正文大题清单在它开始处结束。
- 正文中间逐题给答案解析的学案类文档不算附加部分（没有独立的文末附录块）。
- 文首「参考答案见文末」之类的提及行不算（只认文末真实的附录块）。
- 没有附加部分时省略 appendices 字段。

## 输出格式
严格 JSON，不要输出任何其他文字：
{"sections":[{"name":"听力理解","startMark":"第一部分听力（共两节"},{"name":"阅读理解A","startMark":"The rain had lasted for days"}],"appendices":[{"label":"参考答案","startMark":"参考答案及解析"}]}
一个大题都识别不出时输出 {"sections":[]}。

请严格按照 JSON 格式返回。`;
}
